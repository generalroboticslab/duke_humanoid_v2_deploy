# Every non-adjacent body pair in the self-collision region, generated (not hand-curated).
# A hand-curated list previously missed >60 real-penetrating pairs, confirmed by a 30k-sample
# random joint sweep (2026-07-04, all 14 arm DOFs at full range): own-arm fold-back (e.g.
# GRIPPER_L vs shoulder_3_L, -5cm), cross-arm reach beyond the wrist_3 flange (e.g. GRIPPER_R vs
# shoulder_2_L, -7cm), and flat omissions inconsistent with the covered pattern (base_link vs
# wrist_1_L/R, same magnitude as the already-covered elbow case). Systematic generation can't
# miss a link again when the robot changes. Cost is not a concern: mink's broadphase culling
# made 145 curated pairs cost 0.067ms/call (see mink-upgrade profiling); measured directly on
# the gripper-mounted model after EXCLUDED_COLLISION_PAIRS below (136 raw body-pairs -> 79
# listed -> 140 geom-id combos): mean 0.056ms/call, p99 0.089ms, max 0.123ms.
#
# EXCLUDED_COLLISION_PAIRS additionally drops pairs that add no avoidance value: pose-invariant
# ones (distance doesn't depend on any joint IK can move, either always or never past mink's
# activation margin), pose-dependent ones whose distance still never dips below the margin
# across the sweep (varies with pose but never enough to matter), and ones provably dominated
# by another monitored pair at a proper statistical confidence bound (redundant -- dropping
# loses no coverage). Generated by generate_collision_pair_exclusions.py from a 30k-sample
# joint sweep filtered to physically-reachable (non-self-penetrating) poses; regenerate there
# after any change to geometry, joint limits, or gripper mounting -- do not hand-edit
# humanoid_v21_collision_exclusions.py.
HUMANOID_V21_MINK_COLLISION_PAIRS = [
    (a, b)
    for i, a in enumerate(_SELF_COLLISION_BODIES)
    for b in _SELF_COLLISION_BODIES[i + 1:]
    if frozenset((a, b)) not in _ADJACENT_BODY_PAIRS
    and frozenset((a, b)) not in EXCLUDED_COLLISION_PAIRS
]


_REAL_COLLISION_GROUP = 3  # geom_group convention: real collision-class geoms (contype=1)


def _collect_body_geoms(mj_model, body_name: str) -> list[int]:
    """Geom IDs on `body_name` to use for collision-avoidance: prefer IK-only proxy geoms
    (named ``*_ikproxy*``, e.g. the parallel_gripper rack proxies) if any exist on the body;
    otherwise fall back to real collision-class geoms (``geom_group == 3``). Either way this
    excludes visual-only mesh geoms (group 2, contype 0), which the old "collect everything"
    behavior included as dead weight in every pair.

    Returns [] if `body_name` isn't present on `mj_model` (e.g. a hand-specific body on a
    bare-flange/no-hand model) rather than raising — the pair is then dropped by the empty-list
    check in `_build_mink_geom_pairs`, so hand-specific pairs are simply inert on hand-less
    models instead of crashing IK setup.
    """
    try:
        body_id = mj_model.body(body_name).id
    except KeyError:
        return []
    body_geoms = [i for i in range(mj_model.ngeom) if mj_model.geom_bodyid[i] == body_id]
    proxy_geoms = [i for i in body_geoms if "_ikproxy" in mj_model.geom(i).name]
    if proxy_geoms:
        return proxy_geoms
    return [i for i in body_geoms if mj_model.geom_group[i] == _REAL_COLLISION_GROUP]


def _build_mink_geom_pairs(mj_model, body_pairs, mink=None):
    """Convert body-name collision pairs to Mink geom ID pairs.

    Each side of a pair may be a single body name or a tuple of body names, merged into one
    geom list — e.g. ``("L_left_rack", "L_right_rack")`` expresses "the gripper" as one
    logical unit without duplicating every relationship per rack body. See
    ``_collect_body_geoms`` for the per-body geom-selection rule.
    """
    pairs = []
    for side_a, side_b in body_pairs:
        names_a = (side_a,) if isinstance(side_a, str) else tuple(side_a)
        names_b = (side_b,) if isinstance(side_b, str) else tuple(side_b)
        ga = [g for name in names_a for g in _collect_body_geoms(mj_model, name)]
        gb = [g for name in names_b for g in _collect_body_geoms(mj_model, name)]
        if ga and gb:
            pairs.append((ga, gb))
    return pairs


