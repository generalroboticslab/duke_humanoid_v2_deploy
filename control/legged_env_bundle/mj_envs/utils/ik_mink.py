def _mink_quat_apply(q: np.ndarray, v: np.ndarray) -> np.ndarray:
    """Rotate 3-vector v by wxyz quaternion q (numpy float64)."""
    w, x, y, z = q
    qv = np.array([x, y, z], dtype=np.float64)
    t = 2.0 * np.cross(qv, v)
    return v + w * t + np.cross(qv, t)


def _mink_quat_mul(q1: np.ndarray, q2: np.ndarray) -> np.ndarray:
    """Hamilton product q1 ⊗ q2 for wxyz quaternions (numpy float64)."""
    w1, x1, y1, z1 = q1
    w2, x2, y2, z2 = q2
    return np.array(
        [
            w1 * w2 - x1 * x2 - y1 * y2 - z1 * z2,
            w1 * x2 + x1 * w2 + y1 * z2 - z1 * y2,
            w1 * y2 - x1 * z2 + y1 * w2 + z1 * x2,
            w1 * z2 + x1 * y2 - y1 * x2 + z1 * w2,
        ],
        dtype=np.float64,
    )


class MinHeightTask:
    """Soft one-sided EE-height floor relative to root.

    Zero cost/error while compliant (z >= min_height); pulls upward only when
    violated. Target is recomputed every solve iteration as the frame's OWN
    current pose with z clamped up to the floor (x/y/orientation copied through
    unchanged) -- when compliant this is an exact match to the current pose
    (zero error on every axis), so the task never fights the primary EE task on
    paths that stay above the floor. A hard EE-z gate was rejected earlier
    (blocks picking cubes below the floor) -- this is deliberately soft instead.

    Composes an inner RelativeFrameTask (reusing its tested position-cost QP
    math) rather than deriving a new relative-position Jacobian by hand. Must
    be built from the caller's resolved mink namespace (``mink_ns``), not the
    local vendored classes directly -- ``BatchedMinkIK``'s default
    ``mink_source="local"`` actually resolves to the real installed ``mink``
    package for ``Configuration``/``RelativeFrameTask``/``SE3`` (see
    ``_build_hybrid_mink_namespace``), which is required for EE *site* frames
    (the local vendored ``Configuration`` only supports body frames).
    """

    def __init__(
        self,
        mink_ns,
        frame_name: str,
        frame_type: str,
        root_name: str,
        root_type: str,
        min_height: float,
        cost: float,
        lm_damping: float = 0.0,
    ):
        self._mink = mink_ns
        self._inner = mink_ns.RelativeFrameTask(
            frame_name=frame_name,
            frame_type=frame_type,
            root_name=root_name,
            root_type=root_type,
            position_cost=[0.0, 0.0, float(cost)],
            orientation_cost=[0.0, 0.0, 0.0],
            lm_damping=lm_damping,
        )
        self._frame_name, self._frame_type = frame_name, frame_type
        self._root_name, self._root_type = root_name, root_type
        self._min_height = float(min_height)

    def compute_qp_objective(self, configuration):
        T_fr = configuration.get_transform(
            self._frame_name, self._frame_type, self._root_name, self._root_type
        )
        pose = np.array(T_fr.wxyz_xyz, dtype=np.float64, copy=True)
        if pose[6] < self._min_height:
            pose[6] = self._min_height
        self._inner.set_target(self._mink.SE3(wxyz_xyz=pose))
        return self._inner.compute_qp_objective(configuration)


class NearTargetHeightTask:
    """Soft EE-height floor gated on horizontal proximity to the LIVE commanded target.

    Replaces MinHeightTask's fixed root-frame threshold, which MEMORY.md logs as
    structurally superseded: memoryless (re-measures every QP micro-iteration, no
    persistent "stay above" state) and keyed to a fixed value that can't tell
    "still transiting from home" (legitimately low) from "wrongly low near the
    target" (the actual bug). This task instead reads the SAME arm's primary
    RelativeFrameTask's live target every iteration (``ref_task``) and only
    activates when within ``radius`` of that target's x/y AND below
    ``target.z + height_margin`` -- fully inert (target = current pose, zero
    error) during transit or once above the floor, so it never fights the
    primary task outside the pick zone.

    Composes an inner RelativeFrameTask the same way MinHeightTask does (reuses
    tested position-cost QP math); the only new logic is the horizontal-proximity
    gate read off ``ref_task.transform_target_to_root``.
    """

    def __init__(
        self,
        mink_ns,
        ref_task,
        frame_name: str,
        frame_type: str,
        root_name: str,
        root_type: str,
        height_margin: float,
        radius: float,
        cost: float,
        lm_damping: float = 0.0,
    ):
        self._mink = mink_ns
        self._ref_task = ref_task
        self._inner = mink_ns.RelativeFrameTask(
            frame_name=frame_name,
            frame_type=frame_type,
            root_name=root_name,
            root_type=root_type,
            position_cost=[0.0, 0.0, float(cost)],
            orientation_cost=[0.0, 0.0, 0.0],
            lm_damping=lm_damping,
        )
        self._frame_name, self._frame_type = frame_name, frame_type
        self._root_name, self._root_type = root_name, root_type
        self._height_margin = float(height_margin)
        self._radius = float(radius)

    def compute_qp_objective(self, configuration):
        T_fr = configuration.get_transform(
            self._frame_name, self._frame_type, self._root_name, self._root_type
        )
        pose = np.array(T_fr.wxyz_xyz, dtype=np.float64, copy=True)
        ref_target = self._ref_task.transform_target_to_root
        if ref_target is not None:
            target_xyz = np.asarray(ref_target.wxyz_xyz[4:])
            horiz = np.linalg.norm(pose[4:6] - target_xyz[:2])
            floor_z = target_xyz[2] + self._height_margin
            if horiz < self._radius and pose[6] < floor_z:
                pose[6] = floor_z
        self._inner.set_target(self._mink.SE3(wxyz_xyz=pose))
        return self._inner.compute_qp_objective(configuration)


class BatchedMinkIK:
    """Sequential Mink QP IK with the same public tensor API as batched_ik.BatchedAnalyticalIK.

    Solves IK for ``num_envs`` environments one at a time using Mink's QP backend.
    Each call to ``solve()`` runs ``num_iters`` QP steps per environment and returns
    absolute arm joint positions.

    Not thread-safe: ``_mink_config`` is a single shared MjData object mutated in the
    environment loop — do not call ``solve()`` from multiple threads simultaneously.

    State tensors (device)
    ----------------------
    q_ik : (num_envs, nq) float32
        Warm-start qpos for the next solve.  Non-arm DOFs track ``physics_qpos`` each
        step; arm DOFs are updated by the QP solver.  Mutable — use ``reset()`` to
        resync after episode resets rather than writing directly.

    dq_target / ddq_target : (num_envs, 2*K) float32
        Trajectory filter velocity and acceleration; exact filter states, no finite
        differencing.  Read-only outputs; available for feedforward torque use.
    """

    def __init__(
        self,
        mj_model,
        wp_model=None,  # compatibility; accepted positionally but not used
        num_envs: int = 1,
        device: str = "cpu",
        ee_left_name: str = "",
        ee_right_name: str = "",
        left_joint_names: Optional[List[str]] = None,
        right_joint_names: Optional[List[str]] = None,
        ee_left_type: EEFrameType = "body",
        ee_right_type: EEFrameType = "body",
        limit_margin: float = 0.05, # ~ 3 deg
        ki: float = 0.005,
        ki_max: float = 0.05,
        ki_ori: float = 0.005,
        ki_ori_max: float = 0.05,
        ki_decay: float = 0.99, # both for pos/ori integrals
        max_dq: float = 0.5,
        max_target_pos_step: float = 0.005,
        max_target_ori_step_rad: float = 0.05,
        arm_traj_omega: float = 15.0,
        arm_traj_max_dq_out: float = 10.0,
        arm_traj_max_ddq: float = 40.0,
        debug: bool = False,
        step_dt: float = 0.02,
        backend: str = "mink",
        collision_body_pairs: Sequence[tuple[str | Sequence[str], str | Sequence[str]]] = HUMANOID_V21_MINK_COLLISION_PAIRS,
        mink_solver: str = "daqp",
        mink_damping: float = 1e-2,
        mink_lm_damping: float = 2.0,
        mink_position_cost: float = 5.0,
        mink_orientation_cost: Optional[Sequence[float]] = None,
        mink_posture_weight: float = 0.05,
        mink_min_ee_height: Optional[float] = None,
        mink_min_ee_height_cost: float = 1.0,
        mink_min_ee_height_side: Optional[str] = None,
        mink_near_target_height_margin: Optional[float] = None,
        mink_near_target_radius: float = 0.15,
        mink_near_target_height_cost: float = 1.0,
        mink_near_target_height_side: Optional[str] = None,
        collision_min_distance: float = 0.05,
        collision_detection_distance: float = 0.05,
        mink_source: str = "local",
        root_body_name: str = "base_link",
        mink_nosolution_backoff_threshold: int = 3,
        mink_nosolution_cooldown_steps: int = 4,
        use_yaw_frame: bool = True,
        **_batched_ik_compat,  # absorbs unused batched_ik.py kwargs (wp_model, damping, gain, …)
    ):
        """Initialise solver.

        Args:
            mj_model: MuJoCo model (``mujoco.MjModel``).
            num_envs: Number of parallel environments to solve sequentially.
            device: Torch device string for all output tensors.
            ee_left_name: MuJoCo frame name of the left end-effector.
            ee_right_name: MuJoCo frame name of the right end-effector.
            ee_left_type: Frame type for left EE — ``"body"`` or ``"site"``.
            ee_right_type: Frame type for right EE — ``"body"`` or ``"site"``.
            left_joint_names: Ordered left arm joint names (K joints).
            right_joint_names: Ordered right arm joint names (K joints).
            limit_margin: Joint limit safety margin (rad). IK clamps inside
                [lower + margin, upper - margin].
            ki / ki_max: Position integrator gain and per-axis saturation (world frame).
            ki_ori / ki_ori_max: Orientation integrator gain and norm saturation.
            ki_decay: Exponential decay applied to both integrals each step.
            max_dq: Per-joint velocity limit (rad/s) passed to Mink VelocityLimit.
            max_target_pos_step: Max EE position target displacement per step (m).
            max_target_ori_step_rad: Max EE orientation target change per step (rad).
            smooth_near_alpha / smooth_near_thresh / smooth_far_thresh / output_lpf_beta:
                Legacy smoothing params; accepted for call-site compatibility, silently unused.
            arm_traj_omega: Bandwidth (rad/s) of the critically-damped trajectory filter.
                τ ≈ 1/ω; default 15 rad/s → ~67 ms time constant.
            arm_traj_max_dq_out: Max joint velocity (rad/s) in trajectory output.
            arm_traj_max_ddq: Max joint acceleration (rad/s²); directly caps base reaction force.
            debug: Print solver warnings (NoSolutionFound events).
            step_dt: Control timestep (s); used for velocity / acceleration estimation.
            backend: Accepted for API compatibility; must be one of
                ``"mink" | "auto" | "cpu" | "warp"``.
            collision_body_pairs: Body-name pairs for Mink CollisionAvoidanceLimit. Each side
                may be a single body name or a tuple of body names merged into one geom set.
            mink_solver: QP solver name passed to ``mink.solve_ik()`` (e.g. ``"daqp"``).
            mink_damping: Regularisation damping passed to ``mink.solve_ik()``.
            mink_lm_damping: Levenberg-Marquardt damping for FrameTask.
            mink_position_cost: Position tracking cost weight for FrameTask.
            mink_orientation_cost: 3-element orientation cost per axis [x, y, z].
                Defaults to [1.0, 1.0, 0.01] (relaxed wrist-roll).
            mink_posture_weight: PostureTask cost; 0 disables the task entirely.
            mink_min_ee_height: Soft EE-height floor (root/base_link frame, both arms).
                None disables (default, no behavior change). Pulls the EE up only
                when below this z; zero cost/error while compliant, so it never
                blocks a below-floor pick target -- see MinHeightTask docstring.
            mink_min_ee_height_cost: Position-cost weight (z-axis only) for the
                height-floor task when enabled. Unused if mink_min_ee_height is None.
            mink_min_ee_height_side: Restrict the floor to ``"left"`` or ``"right"``;
                None (default) applies to both. The idle arm's resting/folded pose is
                typically well below any reasonable floor, so applying to both would
                continuously fight the idle arm's rest pose every solve iteration --
                pass the reaching side only unless a floor on both arms is intended.
            mink_near_target_height_margin: Soft EE-height floor gated on horizontal
                proximity to the LIVE commanded target (root/base_link frame), not a
                fixed threshold -- see NearTargetHeightTask docstring. None disables
                (default, no behavior change). Replaces mink_min_ee_height's structural
                weakness (memoryless + fixed floor can't discriminate transit-from-home
                vs wrongly-low-near-target); kept as a separate mechanism, not a
                drop-in default, so both can be screened independently.
            mink_near_target_radius: Horizontal (x/y) distance from the live target
                within which the near-target floor can activate. Unused if
                mink_near_target_height_margin is None.
            mink_near_target_height_cost: Position-cost weight (z-axis only) for the
                near-target floor task when enabled. Unused if
                mink_near_target_height_margin is None.
            mink_near_target_height_side: Restrict the near-target floor to ``"left"``
                or ``"right"``; None (default) applies to both. Same idle-arm-fighting
                rationale as mink_min_ee_height_side.
            collision_min_distance: Minimum allowed distance for CollisionAvoidanceLimit.
            collision_detection_distance: Activation range for collision avoidance (m). Default 0.05 — only geom pairs within 5 cm generate QP constraint rows.
            use_yaw_frame: If True, ``quat_targets`` passed to ``solve()`` are interpreted in
                the yaw frame (gravity-aligned, yaw-tracked) rather than root-body frame.
                ``base_quat_wxyz`` must then be provided to ``solve()`` each step so the solver
                can extract the base roll/pitch and convert orientation targets to root-body frame
                before running Mink. Position targets are always root-body frame regardless.
            **_batched_ik_compat: Silently absorbs legacy ``batched_ik.py`` kwargs
                (``wp_model``, ``damping``, ``gain``, ``pos_tol``, etc.) so callers need
                not change their construction call when switching backends.
        """
        # Validation and defaults.
        if left_joint_names is None:
            left_joint_names = []
