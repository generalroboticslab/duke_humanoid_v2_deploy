    def reset(self, env_ids: torch.Tensor, current_physics_qpos: torch.Tensor):
        """Sync warm-start, integrators, and trajectory-profile state for reset envs."""
        if not self._posture_initialized:
            self._posture_initialized = True
        self.q_ik[env_ids] = current_physics_qpos[env_ids].clone()
        self.ee_integral[env_ids] = 0.0
        self.ori_integral[env_ids] = 0.0
        self._last_ee_pos_ik_base[env_ids] = 0.0
        self._last_ee_quat_ik_base[env_ids] = torch.tensor([1.0, 0.0, 0.0, 0.0], device=self.device)
        self._ik_saturated[env_ids] = False
        arm_q = current_physics_qpos[env_ids][:, self._arm_qpos_addr]
        self._traj_q[env_ids] = arm_q
        self._traj_dq[env_ids] = 0.0
        self._pos_target_init_mask[env_ids] = False
        self._quat_target_init_mask[env_ids] = False
        self.dq_target[env_ids] = 0.0
        self.ddq_target[env_ids] = 0.0
        env_ids_np = env_ids.detach().cpu().numpy()
        self._mink_nosolution_streak[env_ids_np] = 0
        self._mink_cooldown_steps_left[env_ids_np] = 0

        if self._mink_use_posture:
            ref_idx = int(env_ids.flatten()[0].item())
            self._mink_config.data.qpos[:] = current_physics_qpos[ref_idx].detach().cpu().double().numpy()
            self._mink_config.update()
            self._mink_posture_task.set_target_from_configuration(self._mink_config)

    def solve(
        self,
        physics_qpos: torch.Tensor,
        pos_targets: torch.Tensor,
        quat_targets: torch.Tensor,
        num_iters: int = 2,
        actual_ee_pos: Optional[torch.Tensor] = None,
        actual_ee_quat: Optional[torch.Tensor] = None,
        base_quat_wxyz: Optional[torch.Tensor] = None,
    ) -> torch.Tensor:
        """Run Mink IK and return absolute arm joint positions.

        Args:
            physics_qpos: (num_envs, nq) current simulation qpos; used to sync
                non-arm DOFs in the warm start before each solve.
            pos_targets: (num_envs, 2, 3) desired EE positions in **root body frame**.
                Index 0 = left EE, 1 = right EE.
            quat_targets: (num_envs, 2, 4) desired EE orientations. Frame depends on
                ``use_yaw_frame``: root body frame when False (default), yaw frame
                (gravity-aligned, yaw-tracked) when True.
                Index 0 = left EE, 1 = right EE.
            num_iters: QP iterations per environment.  Higher values improve convergence
                but cost proportionally more CPU time.
            actual_ee_pos: (num_envs, 2, 3) observed EE positions in **root body frame**.
                Must match the frame of pos_targets. Drives the position integrator when ki > 0.
            actual_ee_quat: (num_envs, 2, 4) observed EE orientations in **root body frame**,
                wxyz convention. Drives the orientation integrator when ki_ori > 0.
            base_quat_wxyz: (num_envs, 4) or (4,) base orientation in world frame, wxyz
                convention (e.g. from IMU). Required when ``use_yaw_frame=True``; ignored
                otherwise.

        Returns:
            (num_envs, 2*K) absolute arm joint positions, clamped to IK joint limits.
        """
        self.q_ik[:, self._non_arm_mask] = physics_qpos[:, self._non_arm_mask]

        if self._use_yaw_frame:
            if base_quat_wxyz is None:
                raise ValueError("use_yaw_frame=True requires base_quat_wxyz in solve()")
            quat_targets = self._yaw_to_base_quat(quat_targets, base_quat_wxyz)

        pos_targets = self._rate_limit_pos(pos_targets)
        quat_targets = self._rate_limit_quat(quat_targets)
        pos_targets, quat_targets = self._apply_integrators(
            pos_targets, quat_targets, actual_ee_pos, actual_ee_quat
        )

        self._solve_mink(pos_targets, quat_targets, num_iters)

        q_cmd = torch.clamp(
            self.q_ik[:, self._arm_qpos_addr],
            self._joint_lower_ik,
            self._joint_upper_ik,
        )
        self.q_ik[:, self._arm_qpos_addr] = q_cmd

        result = self._apply_trajectory_profile(q_cmd)
        self._update_last_ee_from_smoothed_q(result)
        self._debug_step += 1
        return result

    def _yaw_to_base_quat(
        self, quat_targets: torch.Tensor, base_quat_wxyz: torch.Tensor
    ) -> torch.Tensor:
        """Convert EE orientation targets from yaw frame to root-body frame.

        Yaw frame = world frame with only the yaw (Z-axis) rotation applied; roll and
        pitch are stripped out.  Targets in this frame are gravity-aligned and
        robot-heading-relative, which is natural for manipulation tasks where the base
        tilts under arm loading but the desired grasp orientation should remain fixed
        relative to gravity.

        Derivation:
            q_WY = yaw-only component of q_WB (pure Z rotation)
            q_target_base = q_WB_inv ⊗ q_WY ⊗ q_target_yaw

        Args:
            quat_targets: (num_envs, 2, 4) EE orientation targets in yaw frame, wxyz.
            base_quat_wxyz: (num_envs, 4) or (4,) base orientation in world frame from
                IMU, wxyz convention.

        Returns:
            (num_envs, 2, 4) EE orientation targets in root-body frame.
        """
        if base_quat_wxyz.dim() == 1:
            base_quat_wxyz = base_quat_wxyz.unsqueeze(0)
        base_quat_wxyz = base_quat_wxyz.to(dtype=quat_targets.dtype, device=quat_targets.device)
        w, x, y, z = base_quat_wxyz.unbind(-1)
        yaw = torch.atan2(2.0 * (w * z + x * y), 1.0 - 2.0 * (y * y + z * z))
        zeros = torch.zeros_like(yaw)
        q_WY = torch.stack([torch.cos(yaw * 0.5), zeros, zeros, torch.sin(yaw * 0.5)], dim=-1)
        q_conv = _quat_multiply(
            _quat_conjugate(base_quat_wxyz), q_WY
        )  # (num_envs, 4): takes yaw-frame vector to base frame
        return _quat_multiply(q_conv.unsqueeze(1).expand_as(quat_targets), quat_targets)

    def _rate_limit_pos(self, pos_targets: torch.Tensor) -> torch.Tensor:
        """Clamp per-step EE position target displacement to ``max_target_pos_step``.

        On first call per environment (before init_mask is set) the raw target is
        committed as-is, avoiding a one-step jump from the zero initialisation.
        """
        init_mask = self._pos_target_init_mask
        if (~init_mask).any():
            self._pos_targets_committed[~init_mask] = pos_targets[~init_mask]
            init_mask[~init_mask] = True
        if self._max_target_pos_step < float("inf"):
            delta = pos_targets - self._pos_targets_committed
            dist = delta.norm(dim=-1, keepdim=True).clamp(min=1e-8)
            scale = (self._max_target_pos_step / dist).clamp(max=1.0)
            self._pos_targets_committed = self._pos_targets_committed + delta * scale
        else:
            self._pos_targets_committed.copy_(pos_targets)
        return self._pos_targets_committed

    def _rate_limit_quat(self, quat_targets: torch.Tensor) -> torch.Tensor:
        """Clamp per-step orientation target change to ``max_target_ori_step_rad``.

        Uses axis-angle magnitude to measure the angular step; limits via slerp-style
        scaling of the delta quaternion before composing with the committed target.
        """
        init_mask = self._quat_target_init_mask
        if (~init_mask).any():
            self._quat_targets_committed[~init_mask] = quat_targets[~init_mask]
            init_mask[~init_mask] = True
        if self._max_target_ori_step_rad < float("inf"):
            q_delta = _quat_multiply(quat_targets, _quat_conjugate(self._quat_targets_committed))
            aa_delta = _quat_to_axis_angle(q_delta)
            ang = aa_delta.norm(dim=-1, keepdim=True).clamp(min=1e-8)
            scale = (self._max_target_ori_step_rad / ang).clamp(max=1.0)
            q_step = _axis_angle_to_quat(aa_delta * scale)
            self._quat_targets_committed = _quat_multiply(q_step, self._quat_targets_committed)
            self._quat_targets_committed = self._quat_targets_committed / self._quat_targets_committed.norm(
                dim=-1, keepdim=True
            ).clamp(min=1e-12)
        else:
            self._quat_targets_committed.copy_(quat_targets)
        return self._quat_targets_committed

    def _apply_integrators(
        self,
        pos_targets: torch.Tensor,
        quat_targets: torch.Tensor,
        actual_ee_pos: Optional[torch.Tensor],
        actual_ee_quat: Optional[torch.Tensor],
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Apply bounded integral correction in root-body frame.

        Error = committed_target - actual_ee. With ki_decay=1.0 this drives actual → committed
        at steady state (integral converges to δ, the model mismatch). Using _last_ee_pos_ik_base
        instead causes integral to ramp unbounded (err = δ constant → integral += ki*δ forever).

        Transient windup (integral accumulates during approach) is bounded by ki_max and ki_decay.
        Keep ki small and ki_decay < 1 to limit overshoot on hardware.

        actual_ee_pos / actual_ee_quat must be in root-body frame (same as pos_targets).
        """
        if actual_ee_pos is not None and self._ki > 0.0:
            err_b = self._pos_targets_committed - actual_ee_pos
            self.ee_integral.mul_(self._ki_decay).add_(self._ki * err_b)
            self.ee_integral.clamp_(-self._ki_max, self._ki_max)
            if self.debug and self._debug_step % 100 == 0:
                L_mm = (self.ee_integral[0, 0] * 1000).detach().cpu().numpy()
                R_mm = (self.ee_integral[0, 1] * 1000).detach().cpu().numpy()
                print(f"[IK-mink] ki_delta step={self._debug_step} L=[{L_mm[0]:.1f},{L_mm[1]:.1f},{L_mm[2]:.1f}]mm R=[{R_mm[0]:.1f},{R_mm[1]:.1f},{R_mm[2]:.1f}]mm")
            pos_targets = pos_targets + self.ee_integral

        if actual_ee_quat is not None and self._ki_ori > 0.0:
            err_aa_b = _quat_to_axis_angle(
                _quat_multiply(self._quat_targets_committed, _quat_conjugate(actual_ee_quat))
            )
            self.ori_integral.mul_(self._ki_decay).add_(self._ki_ori * err_aa_b)
            nrm = self.ori_integral.norm(dim=-1, keepdim=True).clamp(min=1e-8)
            self.ori_integral.mul_(nrm.clamp(max=self._ki_ori_max) / nrm)
            quat_targets = _quat_multiply(_axis_angle_to_quat(self.ori_integral), quat_targets)

        return pos_targets, quat_targets

    def _solve_mink(self, pos_targets: torch.Tensor, quat_targets: torch.Tensor, num_iters: int) -> None:
        """Run sequential Mink IK and refresh cached base-frame EE state.

        Invariants: targets already in root-body frame; freejoint pinned to identity before
        every ``config.update()``; preallocated buffers reused; ``_mink_config`` is shared and
        not re-entrant.
        """
        mink = self._mink
        config = self._mink_config
        data = config.data
        pos_np = pos_targets.detach().cpu().double().numpy()
        quat_np = quat_targets.detach().cpu().double().numpy()
        np.copyto(self._q_ik_np, self.q_ik.detach().cpu().double().numpy())
        ee_l_name = self._ee_left_name
        ee_r_name = self._ee_right_name
        root_name = self._root_body_name

        for env_id in range(self.num_envs):
            cooldown_left = self._mink_cooldown_steps_left[env_id]
            if cooldown_left > 0:
                self._mink_cooldown_steps_left[env_id] = cooldown_left - 1
                continue

            # Target construction: pos/quat already in root body frame.
            self._se3_left_buf[:4] = quat_np[env_id, 0]
            self._se3_left_buf[4:] = pos_np[env_id, 0]
            self._se3_right_buf[:4] = quat_np[env_id, 1]
            self._se3_right_buf[4:] = pos_np[env_id, 1]
            self._mink_left_task.set_target(mink.SE3(wxyz_xyz=self._se3_left_buf))
            self._mink_right_task.set_target(mink.SE3(wxyz_xyz=self._se3_right_buf))

            for _ in range(num_iters):
                np.copyto(data.qpos, self._q_ik_np[env_id])
                # RelativeFrameTask is freejoint-invariant. Pin the local config's
                # freejoint to identity so final FK readout lands in root-body frame.
                if data.qpos.shape[0] >= 7:
                    data.qpos[0:3] = 0.0
                    data.qpos[3] = 1.0
                    data.qpos[4:7] = 0.0
                config.update()

                try:
                    vel = mink.solve_ik(
                        config,
                        self._mink_tasks,
                        dt=1.0,
                        solver=self._mink_solver,
                        damping=self._mink_damping,
                        limits=self._mink_limits,
                        constraints=self._mink_constraints,
                        safety_break=False,
                    )
                    self._mink_nosolution_streak[env_id] = 0
                except (mink.NoSolutionFound, NoSolutionFound):
                    streak = self._mink_nosolution_streak[env_id] + 1
                    self._mink_nosolution_streak[env_id] = streak
                    if streak >= self._mink_nosolution_backoff_threshold:
                        self._mink_cooldown_steps_left[env_id] = self._mink_nosolution_cooldown_steps
                        self._mink_nosolution_streak[env_id] = 0
                        if self.debug:
                            print(
                                f"[IK-mink] NoSolutionFound env={env_id}; entering cooldown "
                                f"{self._mink_nosolution_cooldown_steps} steps"
                            )
                    elif self.debug:
                        print(f"[IK-mink] NoSolutionFound env={env_id}; holding previous pose")
                    continue

                self._q_ik_np[env_id, self._mink_arm_qpos_ids_np] = np.clip(
                    self._q_ik_np[env_id, self._mink_arm_qpos_ids_np] + vel[self._mink_arm_dof_ids_np],
                    self._mink_joint_lower_np,
                    self._mink_joint_upper_np,
                )

            # Final FK with converged qpos; readout is in root-body frame via get_transform.
            np.copyto(data.qpos, self._q_ik_np[env_id])
            if data.qpos.shape[0] >= 7:
                data.qpos[0:3] = 0.0
                data.qpos[3] = 1.0
                data.qpos[4:7] = 0.0
            config.update()
            T_l = config.get_transform(ee_l_name, self._ee_left_type, root_name, "body")
            T_r = config.get_transform(ee_r_name, self._ee_right_type, root_name, "body")
            self._ee_quat_np[env_id, 0] = T_l.wxyz_xyz[:4].astype(np.float32)
            self._ee_pos_np[env_id, 0] = T_l.wxyz_xyz[4:].astype(np.float32)
            self._ee_quat_np[env_id, 1] = T_r.wxyz_xyz[:4].astype(np.float32)
            self._ee_pos_np[env_id, 1] = T_r.wxyz_xyz[4:].astype(np.float32)

        self.q_ik.copy_(torch.from_numpy(self._q_ik_np).float().to(self.device))

    def _apply_trajectory_profile(self, q_cmd: torch.Tensor) -> torch.Tensor:
        """Smooth the raw IK joint command before sending to actuators.

        Instead of jumping straight to q_cmd, the trajectory state (_traj_q,
        _traj_dq) chases it like a mass on a critically-damped spring: it
        accelerates toward the target, then decelerates to stop exactly there
        with no overshoot.

        The acceleration is hard-clamped to max_ddq.  Because arm acceleration
        is what pushes/pulls the robot base (Newton's 3rd law through the
        kinematic chain), this cap directly limits how much the base gets
        disturbed when the arm target changes suddenly.

        Outputs dq_target / ddq_target come straight from the filter state —
        no finite differencing — so they are clean feedforward signals for the
        actuator inverse-dynamics loop.
        """
        dt = self._step_dt
        # Spring acceleration toward target, with velocity damping term.
        # ω² sets how aggressively to chase; 2ω damps to prevent overshoot.
        ddq = self._traj_omega_sq * (q_cmd - self._traj_q)
        ddq.add_(self._traj_dq, alpha=-self._traj_2omega)
        # Hard cap on acceleration — this is the base-disturbance budget.
        ddq.clamp_(-self._traj_max_ddq, self._traj_max_ddq)
        # Euler integrate: velocity then position.
        self._traj_dq.add_(ddq, alpha=dt)
        self._traj_dq.clamp_(-self._traj_max_dq, self._traj_max_dq)
        self._traj_q.add_(self._traj_dq, alpha=dt)
        result = self._traj_q.clamp(self._joint_lower_ik, self._joint_upper_ik)
        self.q_ik[:, self._arm_qpos_addr] = result
        self.dq_target.copy_(self._traj_dq)
        self.ddq_target.copy_(ddq)
        return result

    def _update_last_ee_from_smoothed_q(self, q_cmd: Optional[torch.Tensor] = None) -> None:
        """Recompute base-frame EE pose from smoothed arm command.

        Keep `_last_ee_*_ik_base` aligned with command sent to actuators so
        integrator error is computed against same commanded state.
        """
        config = self._mink_config
        data = config.data
        ee_l_name = self._ee_left_name
        ee_r_name = self._ee_right_name
        root_name = self._root_body_name

        if q_cmd is None:
            np.copyto(self._q_ik_np, self.q_ik.detach().cpu().double().numpy())
        else:
            self._q_ik_np[:, self._mink_arm_qpos_ids_np] = q_cmd.detach().cpu().double().numpy()
        for env_id in range(self.num_envs):
            np.copyto(data.qpos, self._q_ik_np[env_id])
            if data.qpos.shape[0] >= 7:
                data.qpos[0:3] = 0.0
                data.qpos[3] = 1.0
                data.qpos[4:7] = 0.0
            config.update()
            T_l = config.get_transform(ee_l_name, self._ee_left_type, root_name, "body")
            T_r = config.get_transform(ee_r_name, self._ee_right_type, root_name, "body")
            self._ee_quat_np[env_id, 0] = T_l.wxyz_xyz[:4].astype(np.float32)
            self._ee_pos_np[env_id, 0] = T_l.wxyz_xyz[4:].astype(np.float32)
            self._ee_quat_np[env_id, 1] = T_r.wxyz_xyz[:4].astype(np.float32)
            self._ee_pos_np[env_id, 1] = T_r.wxyz_xyz[4:].astype(np.float32)

        self._last_ee_pos_ik_base.copy_(torch.from_numpy(self._ee_pos_np).to(self.device))
        self._last_ee_quat_ik_base.copy_(torch.from_numpy(self._ee_quat_np).to(self.device))


