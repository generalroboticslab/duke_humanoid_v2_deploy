"""Mink-only inverse kinematics for two-armed humanoids.

Public API is identical to ``batched_ik.py`` (``BatchedAnalyticalIK`` alias preserved).
Uses only Mink's MuJoCo QP backend — no Warp, no custom DLS kernels, no capsule repulsion.

Frame convention
----------------
All IK data flow is in the **root body frame** (default ``base_link``). ``pos_targets``,
``quat_targets``, ``actual_ee_pos``, ``actual_ee_quat`` passed to ``solve()`` are all
expressed in that frame. ``_solve_mink`` feeds them directly to
``RelativeFrameTask(root=<root_body>)`` — no world conversion, no dependence on the
freejoint qpos. Readouts ``_last_ee_pos_ik_base`` / ``_last_ee_quat_ik_base`` are
returned in the same root-body frame. This matches the deployment sensor stack
(base-mounted or EE-mounted cameras report directly in body frames) and eliminates
the base-pose estimator (VICON / IMU / odometry) from the IK correctness path.
"""

